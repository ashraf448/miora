const greetings = ["مرحبا", "اهلا", "هاي", "السلام عليكم", "صباح الخير", "مساء الخير", "ازيك", "hello", "hi"].map(normalize);

export function getAssistantReply(input) {
  const raw = input.trim();

  if (detectCrisis(raw)) {
    return {
      id: "crisis",
      crisis: true,
      text: "أنا آسف جدًا إنك بتحس كده، وإنت مش لوحدك. سلامتك أهم حاجة دلوقتي.",
      tips: [
        "لو في خطر فوري عليك: اتصل بالإسعاف على 123 أو روح لأقرب طوارئ.",
        "كلّم حد قريب منك دلوقتي، واطلب منه يفضل معاك.",
        "الأمانة العامة للصحة النفسية: 16328. وصندوق مكافحة الإدمان: 16023 (24 ساعة، مجاني وسري).",
      ],
      links: [],
    };
  }

  const t = normalize(raw);
  const matched = topics.find((topic) => topic.keys.some((k) => t.includes(normalize(k))));
  if (matched) return matched;

  if (greetings.some((g) => t === g || t.startsWith(`${g} `))) {
    return {
      id: "greeting",
      text: "أهلًا بيك 🌿 أنا هنا أسمعك. تحب تحكيلي إيه اللي شاغلك النهارده؟",
      tips: [],
      links: [],
    };
  }

  return fallback;
}
