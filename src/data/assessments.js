export const getAssessment = (id) => assessments.find((a) => a.id === id);

/** نحسب النسبة المئوية ونرجّع الفئة المناسبة */
export function evaluate(assessment, answers) {
  const max = assessment.questions.length * 4;
  const total = answers.reduce((sum, v) => sum + (v ?? 0), 0);
  const percent = Math.round((total / max) * 100);
  const result = assessment.results.find((r) => percent <= r.upTo) ?? assessment.results.at(-1);
  return { total, max, percent, result };
}
